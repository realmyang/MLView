"""MLV-P11 — render the sample gallery into `docs/gallery/`, on demand.

    PYTHONUTF8=1 python analyzer/tools/gen_gallery.py [--out DIR] [--only MLV101]
                                                      [--clean-only] [--rules-only]
                                                      [--dry-run] [--quiet]

The assets already exist and are invisible. `analyzer/tests/fixtures/rules/` holds
the bad/good pairs that are the **tightest possible illustration of each defect and
its nearest false-positive trap**, sitting in a test directory nobody opens, and
`analyzer/tests/clean/` holds idiomatic correct programs across six framework
shapes — where `samples/README.md` ships two projects, both CIFAR-shaped torch +
sklearn, so a Lightning or HF user has no reference for what good looks like in
their framework.

This is **zero new content**: every page is one of those files, analyzed and
rendered through exactly the pipeline a user's own code goes through, plus an index
that says what each pair is for.

Nothing is committed. ~90 self-contained reports at ~270 KB each is ~25 MB of
generated bytes, so `docs/gallery/` is in `.gitignore` and this script is how you
get it. Run it before a release, before a demo, or when the rule catalogue moves.

**What the index has to be honest about**, because the roadmap makes that a standing
criterion for every part of this product:

* Each page is a **single-file analysis**. The cross-file rules (MLV301, MLV302,
  MLV401, MLV501) structurally cannot fire on one file, and the analyzer says so in
  its own `single_file_analysis` diagnostic. The index repeats it rather than
  letting a reader mistake a short list for a clean bill of health.
* A `_bad.py` fixture that produces **no finding at all** is a real signal about the
  rule, not a rendering failure, so the index marks it rather than hiding it.
* A `_good.py` fixture that produces a finding of the rule it is the negative
  control for is marked too: that is a false positive, and one high-severity false
  positive costs more trust than ten misses.
"""

