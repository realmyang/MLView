from mlview.api import AnalyzeOptions, analyze_to_dict, render_html  # noqa: E402
from mlview.rules.registry import RuleSpec, all_rules, discover_rules  # noqa: E402

FIXTURES = os.path.join(REPO, "analyzer", "tests", "fixtures", "rules")
CLEAN = os.path.join(REPO, "analyzer", "tests", "clean")
DEFAULT_OUT = os.path.join(REPO, "docs", "gallery")

#: What each clean program is a reference for. A framework name is the thing a
#: reader is actually looking for ("what does good look like in Lightning?").
CLEAN_NOTES: Dict[str, str] = {
    "vanilla_torch.py": "A hand-written PyTorch training loop: split, seed, "
                        "zero_grad/backward/step in order, eval() before validation.",
    "lightning_module.py": "The same pipeline as a Lightning module, where the loop "
                           "is the framework's and MLView must not ask for it twice.",
    "hf_trainer.py": "Hugging Face `Trainer`: the loop, the optimizer and the "
                     "evaluation are all inside the framework.",
    "sklearn_pipeline.py": "The scikit-learn answer to leakage: a `Pipeline` fitted "
                           "inside cross-validation, so no transformer ever sees the test fold.",
    "amp_accumulation.py": "Mixed precision plus gradient accumulation - the shape "
                           "that makes a naive train-loop rule fire on correct code.",
    "timeseries_split.py": "`TimeSeriesSplit`: a chronological split, which a rule "
                           "that assumes `train_test_split` would call a missing holdout.",
}


class Page:
    """One rendered report and the facts the index states about it."""

    def __init__(self, title: str, source: str, relative: str) -> None:
        self.title = title
        self.source = source
        self.relative = relative
        self.counts = {"high": 0, "medium": 0, "low": 0}
        self.codes: List[str] = []
        self.nodes = 0
        self.diagnostics: List[str] = []
        self.error: Optional[str] = None

    @property
    def total(self) -> int:
        return sum(self.counts.values())


def _relative(path: str) -> str:
    return os.path.relpath(path, REPO).replace("\\", "/")


def analyze_one(source: str, out_file: str, dry_run: bool) -> Page:
    """Analyze one file and write its report. A failure is recorded, never raised."""
    page = Page(os.path.basename(source), _relative(source), _relative(out_file))
    try:
        graph = analyze_to_dict(AnalyzeOptions(paths=(source,)))
    except Exception as exc:  # a broken fixture must not sink the whole gallery
        page.error = "%s: %s" % (type(exc).__name__, exc)
        return page
    for issue in graph.get("issues", []):
        if issue.get("suppressed"):
            continue
        severity = str(issue.get("severity", "low"))
        if severity in page.counts:
            page.counts[severity] += 1
        code = str(issue.get("code", ""))
        if code and code not in page.codes:
            page.codes.append(code)
    page.codes.sort()
    page.nodes = int(graph.get("stats", {}).get("nodes", 0) or 0)
    for diagnostic in graph.get("diagnostics", []):
        kind = str(diagnostic.get("kind", ""))
        if kind and kind not in page.diagnostics:
            page.diagnostics.append(kind)
    if not dry_run:
        os.makedirs(os.path.dirname(out_file), exist_ok=True)
        try:
            render_html(graph, out_file)
        except Exception as exc:
            page.error = "render failed: %s" % exc
    return page


def rule_pairs(only: Optional[str]) -> List[Tuple[RuleSpec, List[str]]]:
    """Every registered rule with the fixture files that illustrate it."""
    discover_rules()
    if not os.path.isdir(FIXTURES):
        return []
    present = sorted(f for f in os.listdir(FIXTURES) if f.endswith(".py"))
    pairs: List[Tuple[RuleSpec, List[str]]] = []
    for spec in sorted(all_rules(), key=lambda s: s.code):
        if only and spec.code.upper() != only.upper():
            continue
        files = [f for f in present if f.startswith(spec.code + "_")]
        if files:
            pairs.append((spec, files))
    return pairs


def clean_programs() -> List[str]:
    if not os.path.isdir(CLEAN):
        return []
    return sorted(
        os.path.join(CLEAN, name)
        for name in os.listdir(CLEAN)
        if name.endswith(".py") and not name.startswith("_")
    )


# ------------------------------------------------------------------------- the index
def _esc(text: object) -> str:
    return html.escape(str(text), quote=True)


def _counts_cell(page: Page) -> str:
    if page.error:
        return '<span class="err">error</span>'
    if page.total == 0:
        return '<span class="zero">0</span>'
    parts = [
        '<span class="sev-%s">%d %s</span>' % (name, page.counts[name], name)
        for name in ("high", "medium", "low")
        if page.counts[name]
    ]
    return " · ".join(parts)


def _row(page: Page, note: str, flags: Sequence[str]) -> str:
    marks = "".join('<span class="flag">%s</span>' % _esc(f) for f in flags)
    codes = ", ".join(page.codes) if page.codes else "—"
    return (
        "<tr>"
        '<td><a href="%s">%s</a>%s</td>'
        '<td class="counts">%s</td>'
        "<td><code>%s</code></td>"
        '<td class="note">%s</td>'
        "</tr>"
        % (
            _esc(os.path.relpath(page.relative, "docs/gallery").replace("\\", "/")),
            _esc(page.title),
            marks,
            _counts_cell(page),
            _esc(codes),
            _esc(note),
        )
    )


