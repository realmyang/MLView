def _all_pages(
    rules: List[Tuple[RuleSpec, List[Tuple[Page, str, List[str]]]]],
    cleans: List[Page],
) -> List[Page]:
    return list(cleans) + [page for _spec, rendered in rules for page, _n, _f in rendered]


def blindspot_caveat(pages: List[Page]) -> str:
    """The gallery's own blind spot, **measured on this run**.

    GALLERY-FALSE-BLINDSPOT: this paragraph used to be a constant asserting
    that MLV301 / MLV302 / MLV401 / MLV501 "structurally cannot fire here" and
    that "the analyzer says so on every page as a `single_file_analysis`
    diagnostic". Both halves were false on this build. All four fire on their
    own self-contained fixtures - the tables two sections below say so - and
    `core/coverage.single_file_diagnostic` only speaks when an analyzed module
    *imports* a sibling that was left out, which no rule fixture does, so 0 of
    90 pages carried one.

    Telling a reader the tool was blind where it was not is the same failure as
    telling them it looked where it did not; the standing criterion cuts both
    ways. So the numbers come off the run.
    """
    with_note = [p for p in pages if "single_file_analysis" in p.diagnostics]
    cross = [spec.code for spec in all_rules() if spec.enabled and spec.cross_file]
    fired = sorted({c for p in pages for c in p.codes if c in cross})
    quiet = [c for c in sorted(cross) if c not in fired]
    said = (
        "<p><strong>Each page is a single-file analysis.</strong> Any finding that "
        "would have needed a sibling module is missing from it, and nothing on the "
        "page can tell you which: a short list here is not a clean bill of health.</p>"
    )
    said += (
        "<p>%d of %d page(s) carry a <code>single_file_analysis</code> diagnostic. "
        "That diagnostic fires only when an analyzed module <em>imports</em> a sibling "
        "the run left out, so a self-contained fixture gets none — the silence is the "
        "analyzer being accurate about this corpus, not about your project.</p>"
        % (len(with_note), len(pages))
    )
    if cross:
        said += (
            "<p>The rules whose evidence usually lives in another module are %s. "
            "On this run %s fired on at least one single-file page%s.</p>"
            % (
                ", ".join("<code>%s</code>" % _esc(c) for c in sorted(cross)),
                (", ".join("<code>%s</code>" % _esc(c) for c in fired) or "none of them"),
                (" and %s did not"
                 % ", ".join("<code>%s</code>" % _esc(c) for c in quiet)) if quiet else "",
            )
        )
    return said


def write_index(
    out_dir: str,
    rules: List[Tuple[RuleSpec, List[Tuple[Page, str, List[str]]]]],
    cleans: List[Page],
    seconds: float,
) -> str:
    parts: List[str] = [
        "<!doctype html>",
        '<html lang="en"><head><meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width,initial-scale=1">',
        "<title>MLView gallery</title>",
        "<style>%s</style></head><body><main>" % STYLE,
        "<h1>MLView gallery</h1>",
        '<p class="lede">Every rule fixture and every clean reference program, analyzed and '
        "rendered through the same pipeline your own code goes through. Generated by "
        "<code>analyzer/tools/gen_gallery.py</code>; nothing here is committed.</p>",
        '<div class="caveat">',
        blindspot_caveat(_all_pages(rules, cleans)),
        "<p>A <code>_bad.py</code> that reports <strong>0</strong>, or a "
        "<code>_good.py</code> that reports its own rule, is marked below. Both are facts "
        "about the rule rather than about the page.</p>",
        "</div>",
        "<h2>What good looks like</h2>",
        '<p class="lede">Idiomatic, correct programs across six framework shapes. These are '
        "the reference the two bundled samples cannot be, because both of those are "
        "CIFAR-shaped torch + sklearn.</p>",
        "<table><thead><tr><th>Program</th><th>Findings</th><th>Codes</th>"
        "<th>What it demonstrates</th></tr></thead><tbody>",
    ]
    for page in cleans:
        flags = [] if page.total == 0 else ["finding on clean code"]
        parts.append(_row(page, CLEAN_NOTES.get(page.title, ""), flags))
    parts.append("</tbody></table>")

    parts.append("<h2>Rule fixtures</h2>")
    parts.append(
        '<p class="lede">For each rule, the smallest program that triggers it and the '
        "nearest program that must <em>not</em> — the false-positive trap the rule was "
        "written against.</p>"
    )
    for spec, pages in rules:
        parts.append(
            "<h3>%s — %s <code>(%s)</code></h3>"
            % (_esc(spec.code), _esc(spec.title), _esc(spec.severity))
        )
        parts.append(
            "<table><thead><tr><th>Fixture</th><th>Findings</th><th>Codes</th>"
            "<th>Note</th></tr></thead><tbody>"
        )
        for page, note, flags in pages:
            parts.append(_row(page, note, flags))
        parts.append("</tbody></table>")

    total = len(cleans) + sum(len(p) for _s, p in rules)
    parts.append(
        "<footer>%d page(s) rendered in %.1f s from %d rule(s) and %d clean program(s). "
        "Regenerate with <code>python analyzer/tools/gen_gallery.py</code>.</footer>"
        % (total, seconds, len(rules), len(cleans))
    )
    parts.append("</main></body></html>")

    os.makedirs(out_dir, exist_ok=True)
    index = os.path.join(out_dir, "index.html")
    with open(index, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(parts))
        fh.write("\n")
    return index


# -------------------------------------------------------------------------- the driver
def _fixture_note(name: str, code: str) -> Tuple[str, List[str]]:
    stem = name[:-3]
    tail = stem[len(code) + 1:] if stem.startswith(code + "_") else stem
    if tail == "bad":
        return "The defect, as small as it gets.", []
    if tail == "good":
        return "The nearest correct program: this must stay silent.", []
    variant = tail.replace("_", " ")
    if variant.endswith(" good"):
        return "A correct variant (%s) the rule must not fire on." % variant[:-5], []
    return "A further variant of the defect (%s)." % variant.replace(" bad", ""), []


def build(out_dir: str, only: Optional[str], what: str, dry_run: bool, quiet: bool) -> int:
    started = time.time()
    say = (lambda *a: None) if quiet else (lambda *a: print(*a, file=sys.stderr))

    cleans: List[Page] = []
    if what in ("all", "clean"):
        for source in clean_programs():
            name = os.path.basename(source)
            page = analyze_one(source, os.path.join(out_dir, "clean", name[:-3] + ".html"), dry_run)
            cleans.append(page)
            say("clean  %-24s %d node(s), %d finding(s)" % (name, page.nodes, page.total))

    rules: List[Tuple[RuleSpec, List[Tuple[Page, str, List[str]]]]] = []
    if what in ("all", "rules"):
        for spec, files in rule_pairs(only):
            rendered: List[Tuple[Page, str, List[str]]] = []
            for name in files:
                out_file = os.path.join(out_dir, "rules", spec.code, name[:-3] + ".html")
                page = analyze_one(os.path.join(FIXTURES, name), out_file, dry_run)
                note, flags = _fixture_note(name, spec.code)
                # The two facts the index must not hide.
                if name.endswith("_bad.py") and spec.code not in page.codes:
                    flags = list(flags) + ["%s did not fire" % spec.code]
                if "good" in name and spec.code in page.codes:
                    flags = list(flags) + ["FALSE POSITIVE"]
                rendered.append((page, note, flags))
                say("rule   %-24s %d finding(s) %s" % (name, page.total, ",".join(page.codes)))
            rules.append((spec, rendered))

    seconds = time.time() - started
    if dry_run:
        say("dry run: %d page(s) would be written under %s"
            % (len(cleans) + sum(len(p) for _s, p in rules), out_dir))
        return 0
    index = write_index(out_dir, rules, cleans, seconds)
    # The ONE stdout line, because this is a generator a human runs: the path to open.
    print(index)
    return 0


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        prog="gen_gallery",
        description="Render every rule fixture and clean program into docs/gallery/.",
    )
    parser.add_argument("--out", default=DEFAULT_OUT, metavar="DIR",
                        help="where to write (default: docs/gallery, which is gitignored)")
    parser.add_argument("--only", metavar="MLV101", help="one rule code")
    parser.add_argument("--clean-only", action="store_true", help="only the clean programs")
    parser.add_argument("--rules-only", action="store_true", help="only the rule fixtures")
    parser.add_argument("--dry-run", action="store_true",
                        help="analyze everything and report, writing nothing")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args(list(argv) if argv is not None else None)
    what = "clean" if args.clean_only else "rules" if args.rules_only else "all"
    return build(os.path.abspath(args.out), args.only, what, args.dry_run, args.quiet)


if __name__ == "__main__":
    raise SystemExit(main())
